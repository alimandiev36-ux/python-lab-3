# Назначение программы: вычисление площади и периметра прямоугольника.
# Входные данные: стороны прямоугольника a и b (целые или дробные числа).
# Формулы: площадь S = a * b, периметр P = 2 * (a + b).

# Запрашиваем у пользователя длину первой стороны и преобразуем в float
a = float(input("Введите длину первой стороны (a): "))

# Запрашиваем у пользователя длину второй стороны и преобразуем в float
b = float(input("Введите длину второй стороны (b): "))

# Считаем площадь
S = a * b

# Считаем периметр
P = 2 * (a + b)

# Выводим результаты с двумя знаками после запятой
print(f"Площадь прямоугольника: {S:.2f}")
print(f"Периметр прямоугольника: {P:.2f}")